#!/usr/bin/env python3
"""Embed the game's assets into the Wii executable.

The Wii has no filesystem, so the NintendoWii build links every asset into the
binary. This script concatenates the assets into a single blob (each one padded
to ASSET_ALIGNMENT so that GX texture uploads stay aligned) and writes the C
lookup table that turns an asset path back into an offset/length pair. The blob
itself is assembled into an object file by bin2s, which the CMake build sets up
with dkp_add_embedded_binary_library().

Usage:
    embed-assets.py --source-dir DIR --output-dir DIR [--name NAME] ASSET...

Asset paths are relative to --source-dir and are used verbatim as lookup keys,
e.g. "logo.png" or "tracks/ghost/paths/1.txt".
"""

import argparse
import sys
from pathlib import Path

# GX requires texture data to be 32 byte aligned; padding every asset keeps that
# guarantee for images and costs at most a few hundred bytes.
ASSET_ALIGNMENT = 32


def write_header(path, name, blob_name, blob_symbol):
    path.write_text(
        f"""// Generated by scripts/embed-assets.py - do not edit.
//
// The Wii build has no filesystem, so every asset is linked into the executable
// as one blob. EmbeddedAssets_Find() turns a path such as "tracks/ghost/info.txt"
// into the bytes of that file.
#pragma once

#include <stddef.h>
#include <stdint.h>

typedef struct EmbeddedAsset {{
	const char* path; // relative to the asset directory, e.g. "skybox/+x.png"
	size_t size;

	// Offset of the asset in {blob_name}, so the table needs no relocations.
	size_t offset;
}} EmbeddedAsset;

// Every asset, concatenated by bin2s (see the NintendoWii branch of
// CMakeLists.txt).
extern const uint8_t {blob_symbol}[];

// Returns the asset stored at path, or NULL when there is no such asset.
const EmbeddedAsset* EmbeddedAssets_Find(const char* path);
""",
        encoding="utf-8",
    )


def write_source(path, name, blob_symbol, entries):
    table = "\n".join(
        f'\t{{"{asset}", {size}, {offset}}},' for asset, offset, size in entries
    )
    path.write_text(
        f"""// Generated by scripts/embed-assets.py - do not edit.
#include "{name}.h"

#include <stdlib.h>
#include <string.h>

// Assembled from {name}.dat by bin2s; declared here rather than by including its
// generated header so that this file does not depend on the order the build
// generates it in.
extern const uint8_t {blob_symbol}[];

// Sorted by path, which bsearch() below relies on.
static const EmbeddedAsset embeddedAssets[] = {{
{table}
}};

static int CompareAssetPath(const void* path, const void* asset) {{
	return strcmp(path, ((const EmbeddedAsset*)asset)->path);
}}

const EmbeddedAsset* EmbeddedAssets_Find(const char* path) {{
	return bsearch(path, embeddedAssets, sizeof(embeddedAssets) / sizeof(embeddedAssets[0]),
	               sizeof(embeddedAssets[0]), CompareAssetPath);
}}
""",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", required=True, help="directory the asset paths are relative to")
    parser.add_argument("--output-dir", required=True, help="directory to write the blob and C files to")
    parser.add_argument("--name", default="embedded_assets", help="base name of the generated files")
    parser.add_argument("assets", nargs="*", metavar="ASSET", help="asset path relative to --source-dir")
    args = parser.parse_args()

    source_dir = Path(args.source_dir)
    output_dir = Path(args.output_dir)
    assets = sorted(set(args.assets))
    if not assets:
        parser.error("no assets given")

    blob = bytearray()
    entries = []
    for asset in assets:
        data = (source_dir / asset).read_bytes()
        blob.extend(b"\0" * (-len(blob) % ASSET_ALIGNMENT))
        entries.append((asset, len(blob), len(data)))
        blob.extend(data)

    # bin2s names the symbol after the file it embeds, with dots turned into
    # underscores ("embedded_assets.dat" -> "embedded_assets_dat").
    blob_name = f"{args.name}.dat"
    blob_symbol = blob_name.replace(".", "_")
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / blob_name).write_bytes(blob)
    write_header(output_dir / f"{args.name}.h", args.name, blob_name, blob_symbol)
    write_source(output_dir / f"{args.name}.c", args.name, blob_symbol, entries)

    print(f"Embedded {len(entries)} assets ({len(blob)} bytes) from {source_dir} into {blob_name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
